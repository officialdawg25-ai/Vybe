// Splits supabase/migrations/*.sql into small, ordered, individually pasteable pieces in supabase/sql-chunks/.
// Splits only at top-level statement boundaries (aware of comments, quotes and $$ bodies).
import { readdirSync, readFileSync, writeFileSync, mkdirSync, rmSync } from 'node:fs'

const MAX_LINES = Number(process.env.MAX_LINES ?? 60)
const dir = new URL('../supabase/migrations/', import.meta.url)
const out = new URL('../supabase/sql-chunks/', import.meta.url)

function statements(sql) {
  const res = []; let cur = '', i = 0, dollar = null
  while (i < sql.length) {
    const c = sql[i], two = sql.slice(i, i + 2)
    if (dollar) { if (sql.startsWith(dollar, i)) { cur += dollar; i += dollar.length; dollar = null } else cur += sql[i++]; continue }
    if (two === '--') { const e = sql.indexOf('\n', i); const end = e < 0 ? sql.length : e; cur += sql.slice(i, end); i = end; continue }
    if (c === "'") { let j = i + 1; while (j < sql.length && !(sql[j] === "'" && sql[j + 1] !== "'")) j += sql[j] === "'" ? 2 : 1; cur += sql.slice(i, j + 1); i = j + 1; continue }
    if (c === '$') { const m = sql.slice(i).match(/^\$[A-Za-z_]*\$/); if (m) { dollar = m[0]; cur += m[0]; i += m[0].length; continue } }
    cur += c; i++
    if (c === ';') { res.push(cur.trim()); cur = '' }
  }
  if (cur.trim()) res.push(cur.trim())
  return res
}
const label = s => {
  const body = s.replace(/^(\s*--.*\n)+/, '')
  const m = body.match(/^(?:drop \w+ if exists \S+(?: on \S+)?;\s*)?(?:create (?:or replace )?|alter |insert into |grant |revoke )(?:unique )?(?:table (?:if not exists )?|function |policy |trigger |index (?:if not exists )?\S+ on |extension )?([\w.]+)/i)
  return (m?.[1] ?? 'misc').replace(/^public\./, '').replace(/[^\w]+/g, '-').toLowerCase()
}

rmSync(out, { recursive: true, force: true }); mkdirSync(out, { recursive: true })
const all = readdirSync(dir).filter(f => f.endsWith('.sql')).sort().flatMap(f => statements(readFileSync(new URL(f, dir), 'utf8')))
const chunks = []; let cur = []
for (const s of all) {
  const n = cur.join('\n\n').split('\n').length + s.split('\n').length
  if (cur.length && n > MAX_LINES) { chunks.push(cur); cur = [] }
  cur.push(s)
}
if (cur.length) chunks.push(cur)
const index = []
chunks.forEach((c, k) => {
  const name = `${String(k + 1).padStart(2, '0')}-${label(c[0])}.sql`.slice(0, 60).replace(/-+\.sql$/, '.sql')
  writeFileSync(new URL(name, out), c.join('\n\n') + '\n')
  index.push(`${name}  (${c.join('\n').split('\n').length} lines)`)
})
writeFileSync(new URL('README.md', out), `# Run in order\n\nPaste each file into the Supabase SQL editor and press Run, one at a time, 01 → ${chunks.length}.\nEvery piece is safe to re-run if it fails or you are unsure it completed.\nGenerated by \`node scripts/split-sql.mjs\` from \`supabase/migrations/\`; do not edit by hand.\n\n${index.map(l => '- ' + l).join('\n')}\n`)
console.log(`${chunks.length} chunks, ${all.length} statements`)
