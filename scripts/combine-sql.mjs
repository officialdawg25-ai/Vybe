// Builds one pasteable SQL file from a run of migrations, for the Supabase SQL editor.
//  * Where two of the included migrations define the same constraint, policy, function or trigger, only the LAST (most
//    advanced) definition is kept; the earlier one is dropped from the combined file and listed in its header.
//  * Wrapped in a single transaction: it applies completely or not at all.
//  * A pre-flight block refuses to run on a database that is missing the migrations these build on.
// Usage: node scripts/combine-sql.mjs <out> <migration file>...
import { readFileSync, writeFileSync } from 'node:fs'
import { basename } from 'node:path'

const src = readFileSync(new URL('./split-sql.mjs', import.meta.url), 'utf8')
const statements = new Function(src.slice(src.indexOf('function statements'), src.indexOf('const label')) + '; return statements')()
const [out, ...files] = process.argv.slice(2)
if (!out || !files.length) { console.error('usage: node scripts/combine-sql.mjs <out> <migration>...'); process.exit(1) }

const key = s => {
  const b = s.replace(/^(\s*--.*\n)+/, '').replace(/\s+/g, ' ').toLowerCase()
  let m
  if ((m = b.match(/^alter table (?:public\.)?(\w+) (?:drop constraint if exists|add constraint) (\w+)/))) return `constraint ${m[1]}.${m[2]}`
  if ((m = b.match(/^(?:drop policy if exists|create policy) (\w+) on ([\w.]+)/))) return `policy ${m[2]}.${m[1]}`
  if ((m = b.match(/^create or replace function ([\w.]+)\s*\(/))) return `function ${m[1]}`
  if ((m = b.match(/^(?:drop trigger if exists|create trigger) (\w+)/))) return `trigger ${m[1]}`
  return null
}
const all = files.map(f => ({ f: basename(f), stmts: statements(readFileSync(f, 'utf8')) }))
const last = new Map()
all.forEach(({ f, stmts }) => stmts.forEach(s => { const k = key(s); if (k) last.set(k, f) }))
const dropped = []
const body = all.map(({ f, stmts }) => {
  const kept = stmts.filter(s => { const k = key(s); if (k && last.get(k) !== f) { dropped.push(`${k} (from ${f}; superseded by ${last.get(k)})`); return false } return true })
  return `-- ======================================================================== ${f}\n${kept.join('\n')}`
}).join('\n\n')

const header = `-- Combined migrations: ${files.map(f => basename(f)).join(', ')}
-- Generated by scripts/combine-sql.mjs. Do not edit by hand; edit the migrations and regenerate.
-- Runs as ONE transaction (all or nothing) and is safe to run again.
${dropped.length ? `-- Duplicates removed (the later, more advanced definition is kept):\n${[...new Set(dropped)].map(d => `--   ${d}`).join('\n')}` : '-- No duplicate definitions between these migrations.'}
`
const pre = readFileSync(new URL('./combine-preflight.sql', import.meta.url), 'utf8')
const post = readFileSync(new URL('./combine-verify.sql', import.meta.url), 'utf8')
writeFileSync(out, `${header}\nbegin;\n\n${pre.trim()}\n\n${body}\n\ncommit;\n\n${post.trim()}\n`)
console.log(`${out}: ${all.reduce((n, x) => n + x.stmts.length, 0)} statements, ${new Set(dropped).size} superseded definition(s) removed`)
