// Builds supabase/manual/update-19/run-me.sql: migration 19 (organisation portal) as one all-or-nothing file for the
// Supabase SQL editor. It refuses to run until migration 18 is in place and ends with a table of checks.
// Usage: node scripts/sql-update-19.mjs   (rerun after changing migration 19)
import { readFileSync, writeFileSync, mkdirSync } from 'node:fs'

const body = readFileSync(new URL('../supabase/migrations/20261101000019_org_portal.sql', import.meta.url), 'utf8').trim()
const checks = [
  ['identity columns', "exists (select 1 from information_schema.columns where table_name = 'organizations' and column_name = 'cover_path') and exists (select 1 from information_schema.columns where table_name = 'organizations' and column_name = 'links')"],
  ['image and link guard', "exists (select 1 from pg_trigger where tgname = 'org_guard')"],
  ['audit triggers', "exists (select 1 from pg_trigger where tgname = 'org_audit') and exists (select 1 from pg_trigger where tgname = 'org_member_audit')"],
  ['portal functions (members only)', "has_function_privilege('authenticated', 'public.org_overview(uuid)', 'execute') and not has_function_privilege('anon', 'public.org_overview(uuid)', 'execute') and exists (select 1 from pg_proc where proname = 'set_org_member_role') and exists (select 1 from pg_proc where proname = 'org_activity')"],
  ['media read rule includes organisation logos and covers', "(select pg_get_expr(polqual, polrelid) from pg_policy where polname = 'media_select_visible') like '%organizations%'"],
]
const text = `-- MIGRATION 19: Organisation Portal (identity, roles, history, overview)
-- Generated by scripts/sql-update-19.mjs from supabase/migrations/20261101000019_org_portal.sql; do not edit by hand.
-- Paste the WHOLE file into the Supabase SQL editor with nothing selected, then Run. Check the last line you pasted is
-- "-- END OF MIGRATION 19". It runs all or nothing and is safe to run again; the table at the end should say true on every row.

begin;

do $$ begin
  if not ((select pg_get_expr(polqual, polrelid) from pg_policy where polname = 'media_select_visible') like '%l.image_path = objects.name%') then
    raise exception 'Stopped before changing anything: apply migrations 14-18 (supabase/manual/update-14-to-18) first.';
  end if;
end $$;

${body}

commit;

select item, ok from (values
${checks.map(([i, c]) => `  ('${i}', ${c})`).join(',\n')}
) as v(item, ok);
-- END OF MIGRATION 19
`
mkdirSync(new URL('../supabase/manual/update-19/', import.meta.url), { recursive: true })
writeFileSync(new URL('../supabase/manual/update-19/run-me.sql', import.meta.url), text)
console.log(`run-me.sql: ${text.split('\n').length} lines`)
