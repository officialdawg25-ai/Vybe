"""Vectorises the supplied VYBE wordmark raster into per-letter SVG paths (src/brand/logoPaths.ts).
Usage: python3 scripts/trace-logo.py <wordmark.png> > src/brand/logoPaths.ts   (needs: pillow numpy potracer)"""
import sys, json
import numpy as np
from PIL import Image
import potrace

def rdp(pts, eps):
    """Ramer-Douglas-Peucker on a closed ring (split at the two farthest-apart points)."""
    def seg(a, b):
        (x1, y1), (x2, y2) = pts[a], pts[b]; dx, dy = x2 - x1, y2 - y1; n = (dx*dx + dy*dy) ** .5 or 1e-9
        m, k = 0, -1
        for i in range(a + 1, b):
            dd = abs(dy * (pts[i][0] - x1) - dx * (pts[i][1] - y1)) / n
            if dd > m: m, k = dd, i
        if m > eps: return seg(a, k)[:-1] + seg(k, b)
        return [pts[a], pts[b]]
    n = len(pts); i0 = 0
    j = max(range(n), key=lambda i: (pts[i][0]-pts[i0][0])**2 + (pts[i][1]-pts[i0][1])**2)
    a, b = sorted((i0, j))
    return seg(a, b)[:-1] + seg_ring(pts, b, n, a, eps)
def seg_ring(pts, b, n, a, eps):
    ring = pts[b:] + pts[:a + 1]
    sub = rdp_open(ring, eps); return sub[:-1]
def rdp_open(pts, eps):
    if len(pts) < 3: return pts
    (x1, y1), (x2, y2) = pts[0], pts[-1]; dx, dy = x2 - x1, y2 - y1; n = (dx*dx + dy*dy) ** .5 or 1e-9
    m, k = 0, 0
    for i in range(1, len(pts) - 1):
        dd = abs(dy * (pts[i][0] - x1) - dx * (pts[i][1] - y1)) / n
        if dd > m: m, k = dd, i
    if m > eps: return rdp_open(pts[:k + 1], eps)[:-1] + rdp_open(pts[k:], eps)
    return [pts[0], pts[-1]]

def snap(poly, tol):
    """Merge near-equal x and y coordinates so horizontal/vertical edges come out exactly axis-aligned."""
    def cluster(vals):
        order = sorted(set(vals)); groups, cur = [], [order[0]]
        for v in order[1:]:
            if v - cur[-1] <= tol: cur.append(v)
            else: groups.append(cur); cur = [v]
        groups.append(cur)
        m = {}
        for g in groups:
            for v in g: m[v] = sum(g) / len(g)
        return m
    mx, my = cluster([x for x, _ in poly]), cluster([y for _, y in poly])
    return [(mx[x], my[y]) for x, y in poly]

S = 3  # upscale before thresholding for smoother edges
im = Image.open(sys.argv[1]).convert('RGBA')
a = np.array(im)[..., 3]
ys, xs = np.where(a > 128)
x0, x1, y0, y1 = xs.min() - 4, xs.max() + 4, ys.min() - 4, ys.max() + 4
alpha = Image.fromarray(a[y0:y1, x0:x1]).resize(((x1 - x0) * S, (y1 - y0) * S), Image.LANCZOS)
bm = np.array(alpha) > 128
# split letters at empty columns
cols = bm.any(axis=0)
runs, start = [], None
for i, c in enumerate(cols):
    if c and start is None: start = i
    if not c and start is not None: runs.append((start, i)); start = None
if start is not None: runs.append((start, len(cols)))
assert len(runs) == 4, runs
rows = bm.any(axis=1); top, bot = np.where(rows)[0][[0, -1]]
H = bot - top + 1
f = 1 / S
out = {'letters': [], 'height': round(H * f, 1)}
for (l, r), name in zip(runs, 'VYBE'):
    sub = bm[top:bot + 1, l:r]
    # V, Y, E are straight-edged: trace them as polygons. B has true curves.
    pl = potrace.Bitmap(~sub).trace(turdsize=40, alphamax=(1.15 if name == 'B' else 0.0), opttolerance=(3.0 if name == 'B' else 8.0))
    d = []
    fmt = lambda p: f'{p.x * f:.1f} {p.y * f:.1f}'
    for c in pl:
        if name == 'B':  # curved letter: keep the fitted beziers
            d.append('M' + fmt(c.start_point))
            for s in c.segments:
                if s.is_corner: d.append('L' + fmt(s.c) + 'L' + fmt(s.end_point))
                else: d.append('C' + fmt(s.c1) + ' ' + fmt(s.c2) + ' ' + fmt(s.end_point))
            d.append('Z')
        else:  # straight-edged letters: flatten, then simplify to clean polygons
            pts = [(c.start_point.x, c.start_point.y)]
            for s in c.segments:
                if s.is_corner: pts += [(s.c.x, s.c.y), (s.end_point.x, s.end_point.y)]
                else:
                    p0 = pts[-1]
                    for k in range(1, 9):
                        t = k / 8; u = 1 - t
                        pts.append((u**3*p0[0] + 3*u*u*t*s.c1.x + 3*u*t*t*s.c2.x + t**3*s.end_point.x,
                                    u**3*p0[1] + 3*u*u*t*s.c1.y + 3*u*t*t*s.c2.y + t**3*s.end_point.y))
            poly = snap(rdp(pts[:-1], 5.0 * S), 9.0 * S)
            d.append('M' + 'L'.join(f'{x * f:.1f} {y * f:.1f}' for x, y in poly) + 'Z')
    d = ''.join(d)
    out['letters'].append({'id': name, 'x': round(l * f, 1), 'w': round((r - l) * f, 1), 'd': d})
W = round((runs[-1][1]) * f, 1)
out['width'] = W
print('// Generated by scripts/trace-logo.py from the supplied VYBE wordmark raster. Do not edit by hand.')
print('// Coordinates are in the wordmark\'s own space: each letter path starts at x=0; place it at `x`.')
print('export const WORDMARK = ' + json.dumps(out, indent=2) + ' as const')
